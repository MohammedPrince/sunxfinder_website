    public function getCompanies(): Collection
    {
        return SolarCompany::query()
            ->whereIn('status', ['approved', 'pending'])
            ->where('is_active', true)
            ->where('is_verified', true)
            ->orderByDesc('created_at')
            ->get();
    }

