    /** Queues the "new company sign-up" email to the admin. Never fails the sign-up. */
    private function notifyAdminOfNewCompany(SolarCompany $company): void
    {
        try {
            Mail::to(config('mail.admin_notify_address'))->queue(new NewCompanyRegisteredMail([
                'id' => (int) $company->id,
                'name' => (string) $company->name,
                'username' => (string) $company->username,
                'email' => $company->email,
                'phone' => $company->phone,
                'city' => $company->city,
                'registered_at' => now()->format('M d, Y H:i'),
            ]));
        } catch (Throwable $e) {
            report($e);
        }
    }

    public function registerCompany(array $data): array
    {
        try {
            $company = DB::transaction(function () use ($data) {
                $baseSlug = Str::slug($data['name']) ?: 'solar-company';
                $slug = $baseSlug;
                $counter = 1;

                while (SolarCompany::where('slug', $slug)->exists()) {
                    $slug = $baseSlug . '-' . $counter++;
                }

                $company = new SolarCompany();

                $company->name = $data['name'];
                $company->slug = $slug;
                $company->username = $data['username'];
                $company->email = $data['email'];
                $company->phone = $data['phone'];
                $company->city = $data['city'];
                $company->services = $data['services'];
                $company->ar_services = $data['ar_services'];
                $company->description = $data['description'];
                $company->ar_description = $data['ar_description'];
                $company->password = Hash::make($data['password']);
                $company->social_media = $data['social_media'] ?? null;
                $company->year_of_exp = $data['year_of_exp'] ?? null;
                $company->number_of_projects = $data['number_of_projects'] ?? null;

                // The administrator will enter the license number later.
                $company->license_number = null;

                // Logo path generated by the registration controller.
                $company->logo_path = $data['logo_path'] ?? null;

                // Awaiting administrator approval.
                $company->status = 'pending';
                $company->is_verified = false;
                $company->is_active = false;

                $company->save();

                return $company;
            });

            $this->notifyAdminOfNewCompany($company);

            return [
                'success' => true,
                'message' => app()->getLocale() === 'ar'
                    ? 'تم تسجيل حساب شركتك بنجاح. يرجى الانتظار حتى تتم الموافقة على الحساب.'
                    : 'Your company account has been registered successfully. Please wait for approval.',
                'company' => $company,
            ];
        } catch (Throwable $e) {
            report($e);

            return [
                'success' => false,
                'message' => 'Registration could not be completed. Please try again.',
            ];
        }
    }

    public function storeCustomer(array $data)
    {
        try {
            $customer = new Customer();

            $customer->username = $data['username'];
            $customer->full_name = $data['full_name'];
            $customer->phone = $data['phone'];
            $customer->email = $data['email'];
            $customer->gender = $data['gender'];
            $customer->city = $data['city'];
            $customer->address = $data['address'];
            $customer->password = $data['password'];

            $customer->status = 'pending';
            $customer->is_active = false;

            if ($customer->save()) {
                Log::info('Customer registered; dispatching welcome email.', [
                    'customer_id' => $customer->id,
                    'locale' => app()->getLocale(),
                ]);

                SendCustomerWelcomeEmail::dispatch(
                    (int) $customer->id,
                    app()->getLocale()
                )->afterCommit();

                return [
                    'success' => true,
                    'message' => app()->getLocale() === 'ar'
                        ? 'تم تسجيل حسابك بنجاح. يرجى الانتظار حتى تتم الموافقة على حسابك.'
                        : 'Your account has been registered successfully. Please wait for approval.',
                    'customer' => $customer,
                ];
            }

            return [
                'success' => false,
                'message' => app()->getLocale() === 'ar'
                    ? 'تعذّر إكمال التسجيل. يرجى المحاولة مرة أخرى.'
                    : 'Registration could not be completed. Please try again.',
            ];
        } catch (Throwable $e) {
            report($e);

            return [
                'success' => false,
                'message' => app()->getLocale() === 'ar'
                    ? 'تعذّر إكمال التسجيل. يرجى المحاولة مرة أخرى.'
                    : 'Registration could not be completed. Please try again.',
            ];
        }
    }

    /** Store links of the customer app, keyed by platform (android / ios). Empty when none is set. */
    /**
     * Emails a website "Contact us" message to info@sunxfinder.com (queued, so the
     * visitor doesn't wait on SMTP). Reply-To is the visitor's email.
     */
    public function sendContactMessage(array $data): array
    {
        $senderTypes = [
            'customer' => 'Customer / homeowner',
            'company' => 'Solar company',
            'other' => 'Other',
        ];

        try {
            Mail::to(config('mail.contact_address'))->queue(new ContactMessageMail([
                'name' => $data['name'],
                'email' => $data['email'],
                'phone' => $data['phone'] ?? null,
                'sender_type_label' => $senderTypes[$data['sender_type']] ?? 'Other',
                'subject' => $data['subject'],
                'message' => $data['message'],
                'lang' => app()->getLocale(),
                'ip' => request()->ip(),
                'sent_at' => now()->format('d M Y, H:i'),
            ]));

            return ['success' => true];
        } catch (Throwable $e) {
            report($e);

            return ['success' => false];
        }
    }

    public function getAppDownloadLinks(): array
